// The root layout reads Header/Footer/Site Settings from the DB on every
// request (so menu/theme edits show up immediately, no rebuild). That means
// the whole app is request-rendered, not statically generated - force it
// explicitly so Next never tries to prerender any route at build time (which
// would fail on the Cloudflare build machine, which has no real DB/secret
// access).
export const dynamic = 'force-dynamic'

type LinkSource = { label?: string | null; linkType?: string | null; page?: unknown; customUrl?: string | null; openInNewTab?: boolean | null }

export default async function RootLayout(props: { children: React.ReactNode }) {
  const { children } = props
  // Cloudflare's two-letter country for the visitor; drives the cookie banner's opt-in rule.
  const country = (await headers()).get('cf-ipcountry')
  const engine = await getEngine()
  const shopSettings = await engine.findGlobal({ slug: 'shop-settings', depth: 0 }).catch((): null => null)
  const storeCurrency = shopCurrency({ settings: (shopSettings ?? {}) as Record<string, unknown> })
  // Extra display currencies (display only). Empty unless some are set up, so the shop looks the same as before.
  const displayState = await loadDisplayState(storeCurrency, (await cookies()).get(DISPLAY_CURRENCY_COOKIE)?.value)

  const [settings, header, footer, resolvedPages] = (await Promise.all([
    engine.findGlobal({ slug: 'site-settings', depth: 1 }).catch((): null => null),
    engine.findGlobal({ slug: 'header', depth: 1 }).catch((): null => null),
    engine.findGlobal({ slug: 'footer', depth: 1 }).catch((): null => null),
    getAllResolvedPages().catch((): ResolvedPage[] => []),
  ])) as [SiteSetting | null, HeaderGlobal | null, FooterGlobal | null, ResolvedPage[]]

  const pathById = new Map(resolvedPages.map((entry) => [String(entry.page.id), entry]))

  const resolveHref = (item: LinkSource): string | null => {
    if (item.linkType === 'page') {
      const pageId = item.page && typeof item.page === 'object' ? (item.page as { id?: unknown }).id : item.page
      if (!pageId) return null
      const entry = pathById.get(String(pageId))
      if (!entry) return null
      return entry.page.isHomepage ? '/' : `/${entry.path.join('/')}`
    }
    return item.customUrl || null
  }

  const features = settings?.features
  const disabledPrefixes = [
    features?.ecommerce === false ? '/shop' : null,
    features?.ecommerce === false ? '/cart' : null,
    features?.events === false ? '/events' : null,
    features?.blog === false ? '/blog' : null,
    features?.faq === false ? '/faq' : null,
  ].filter((v): v is string => Boolean(v))

  const isAllowed = (href: string) => !disabledPrefixes.some((prefix) => href === prefix || href.startsWith(`${prefix}/`))

  const buildLinks = (items: LinkSource[] | null | undefined): NavLink[] =>
    (items || [])
      .map((item): NavLink | null => {
        const href = resolveHref(item)
        if (!href || !item.label || !isAllowed(href)) return null
        const children = buildLinks((item as { children?: LinkSource[] }).children)
        return { href, label: item.label, newTab: Boolean(item.openInNewTab), children: children.length ? children : undefined }
      })
      .filter((link): link is NavLink => Boolean(link))

  const navLinks = buildLinks(header?.menu)


  // The account area adds one header link of its own, only while it is on.

  if (features?.accounts) navLinks.push({ href: '/account', label: 'Account' })
  const footerColumns = (footer?.columns || []).map((column) => ({
    title: column.title,
    links: buildLinks(column.links).map((l) => ({ href: l.href, label: l.label })),
  }))

  const logo = settings?.logo && typeof settings.logo === 'object' ? (settings.logo as Media) : null
  const theme = settings?.theme

  // Only the installed fonts actually picked for heading or body get CSS,
  // links and preloads; the built-in faces keep coming from @fontsource above.
  const customFonts = sanitizeInstalledFonts((theme as { customFonts?: unknown } | null | undefined)?.customFonts)
  const heading = resolveThemeFont(theme?.headingFont, HEADING_FONT_VARS, 'cormorant', customFonts)
  const body = resolveThemeFont(theme?.bodyFont, BODY_FONT_VARS, 'jost', customFonts)
  const fontsInUse = [heading.installed, body.installed]
    .filter((font): font is InstalledFont => font !== null)
    .filter((font, index, all) => all.findIndex((other) => other.id === font.id) === index)
  const fontCss = buildFontCss(fontsInUse)
  const googleStylesheets = remoteStylesheetUrls(fontsInUse)
  const fontPreloads = preloadLinks(fontsInUse, fontsInUse.map((font) => font.family))
  const usesFontsource = fontsInUse.some((font) => font.source === 'fontsource' && !font.local)

  const themeVars = [
    theme?.primaryColor ? `--color-ink: ${theme.primaryColor};` : '',
    theme?.accentColor ? `--color-gold: ${theme.accentColor};` : '',
    theme?.backgroundColor ? `--color-cream: ${theme.backgroundColor};` : '',
    `--font-display: ${heading.stack};`,
    `--font-body: ${body.stack};`,
    `--radius: ${RADIUS_VALUES[theme?.cornerStyle || 'soft']};`,
  ].join(' ')

  // Global theme styles (colours, text, buttons, tables). A failure here must never break the page.
  let themeStylesCss = ''
  try {
    const { styles, saved } = await loadThemeStyles()
    themeStylesCss = buildThemeStylesCss(styles, {
      saved,
      legacy: {
        primaryColor: theme?.primaryColor || undefined,
        accentColor: theme?.accentColor || undefined,
        backgroundColor: theme?.backgroundColor || undefined,
      },
    }, { fonts: customFonts })
  } catch {
    themeStylesCss = ''
  }

  // Maintenance mode: while it is on, visitors get the maintenance screen in place of the page. Read only
  // when it is on, so the normal path costs nothing extra. Admin API routes, webhooks and feeds never reach
  // this layout (they are route handlers or live outside the (frontend) group).
  const sitePages = await getSitePages()
  const maintenance = sitePages.maintenance
  const showMaintenance = maintenance.enabled
    ? shouldShowMaintenance({
        enabled: true,
        path: (await headers()).get('next-url') ?? '/',
        cookie: (await cookies()).get(BYPASS_COOKIE)?.value ?? null,
        token: maintenance.bypassToken,
        isAdmin: maintenance.allowAdmins ? await isSignedInAdmin() : false,
        allowAdmins: maintenance.allowAdmins,
      })
    : false

  // Language for this request (null while multilingual is off: the document keeps its single-language markup).
  const multilingual = await readMultilingualSettingsFromD1()
  // The logged-in portal takes its language from the visitor (profile, cookie, browser), never from a URL.
  const portal = isPortalPath(requestPathOf(await headers()), multilingual.activeLocales)
  const locale = portal
    ? await currentPortalLocale()
    : requestLocale((await headers()).get(LOCALE_HEADER), multilingual)

  // Header / footer templates (Site templates). Null for each when none matches, and the built-in ones draw.
  const chrome = await renderChromeTemplates(requestPathOf(await headers()))
  const siteEffects = siteEffectsFor(settings, requestPathOf(await headers()))

  const storeDict = await storeTexts()
  return (
    <html
      lang={locale ?? 'en'}
      dir={locale ? directionFor(locale) : undefined}
      data-btn={theme?.buttonStyle || 'solid'}
      data-hover={theme?.hoverEffect || 'fade'}
    >
      <head>
        <SpeedHead />
        {showMaintenance && <meta name="robots" content="noindex" />}
        {googleStylesheets.length > 0 && <link rel="preconnect" href="https://fonts.googleapis.com" />}
        {googleStylesheets.length > 0 && <link rel="preconnect" href="https://fonts.gstatic.com" crossOrigin="anonymous" />}
        {usesFontsource && <link rel="preconnect" href="https://cdn.jsdelivr.net" crossOrigin="anonymous" />}
        {googleStylesheets.map((href) => (
          <link key={href} rel="stylesheet" href={href} />
        ))}
        {fontPreloads.map((preload) => (
          <link key={preload.href} rel="preload" as="font" type={preload.type} href={preload.href} crossOrigin="anonymous" />
        ))}
        {fontCss && <style dangerouslySetInnerHTML={{ __html: fontCss }} />}
      </head>
      <body>
        <ImpersonationBanner />
        <SeoScripts country={country} />
        <SeoJsonLd />
        <AdsRoot />
        <style dangerouslySetInnerHTML={{ __html: `:root { ${FONT_FACE_VARS} }` }} />
        <style dangerouslySetInnerHTML={{ __html: `:root { ${themeVars} }` }} />
        {themeStylesCss && <style id="eg-theme-styles" dangerouslySetInnerHTML={{ __html: themeStylesCss }} />}
        <ShopCurrencyProvider currency={storeCurrency}>
        <DisplayCurrencyProvider state={displayState}>
        <Providers>
        <StoreTextsProvider value={storeDict} locale={await publicLocale()}>
          {chrome.header ? (
            <header>{chrome.header}</header>
          ) : (
          <Header
            siteName={settings?.siteName || undefined}
            logoUrl={logo?.url || undefined}
            logoWidth={logo?.width || undefined}
            logoHeight={logo?.height || undefined}
            showLogo={header?.showLogo !== false}
            navLinks={navLinks}
            sticky={header?.sticky !== false}
            desktopLayout={(header?.desktopLayout as 'logo-left' | 'logo-center' | 'logo-right') || 'logo-left'}
            mobileLayout={(header?.mobileLayout as 'slide-in' | 'fullscreen') || 'slide-in'}
            showCart={features?.ecommerce !== false && header?.showCart !== false}
            announcementBar={header?.announcementBar}
            socials={header?.socials}
          />
          )}
          <AdPlacements position="header" />
          <main>
            {showMaintenance ? <MaintenanceScreen headline={maintenance.headline} message={maintenance.message} /> : children}
          </main>
          <AdPlacements position="footer" />
          {chrome.footer ? (
            <footer>{chrome.footer}</footer>
          ) : (
          <Footer
            siteName={settings?.siteName || undefined}
            logoUrl={logo?.url || undefined}
            logoWidth={logo?.width || undefined}
            logoHeight={logo?.height || undefined}
            showLogo={footer?.showLogo !== false}
            bottomText={footer?.bottomText || undefined}
            columns={footerColumns}
            contactEmail={footer?.contact?.email}
            contactPhone={footer?.contact?.phone}
            address={footer?.contact?.address || undefined}
            socials={footer?.socials}
            layout={(footer?.layout as 'columns-3' | 'columns-4' | 'stacked') || 'columns-3'}
            copyrightText={footer?.copyrightText}
          />
          )}
        </StoreTextsProvider>
        </Providers>
        </DisplayCurrencyProvider>
        </ShopCurrencyProvider>
        {siteEffects && <SiteEffects config={siteEffects} />}
        <SeoBodyScripts />
      </body>
    </html>
  )
}