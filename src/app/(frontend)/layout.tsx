// next/font/google. next/font/google fetches font files from
// fonts.googleapis.com/fonts.gstatic.com during the build; Cloudflare Pages'
// build network doesn't reliably reach those hosts, which crashed the build
// with `TypeError: Cannot read properties of null (reading '1')` inside
// next/font's google loader. @fontsource ships the actual woff2/woff files in
// the package, so there's no network fetch at build time at all.
